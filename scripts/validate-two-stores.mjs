import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const products=JSON.parse(read('site/selection-affiliation.json'));
const page=read('site/affiliation.html'),code=read('site/affiliation.js'),css=read('site/affiliation.css');
assert.equal(products.version,1);
assert.equal(products.affiliateEnabled,false,'No fabricated affiliate commissions');
assert.equal(products.selectionDate,'2026-10-26');
assert.equal(products.products.length,15);
assert.equal(products.tiers.essential.count,6);
assert.equal(products.tiers.signature.count,6);
assert.equal(products.tiers.prestige.count,3);
assert.equal(new Set(products.products.map(p=>p.id)).size,15);
const tiers=products.products.reduce((a,p)=>(a[p.tier]=(a[p.tier]||0)+1,a),{});
assert.deepEqual(tiers,{essential:6,signature:6,prestige:3});
const domains=['casio.com','swatch.com','citizenwatch.eu','orientwatch.fr','seikowatches.com','tissotwatches.com','hamiltonwatch.com'];
for(const p of products.products){
 assert.ok(p.id&&p.brand&&p.model&&p.description&&p.tone);
 assert.equal(p.photoRights,'permission_declared_by_site_owner');
 assert.equal(p.photoReview?.publicUsageApproved,true);
 assert.equal(p.photoReview?.permissionIndependentlyVerified,false);
 assert.equal(p.availability,'not_verified');
 assert.equal(p.affiliateUrl,null);
 assert.equal(p.priceDisplay,false);
 assert.equal(p.merchantLinkStatus,'untracked_official');
 const u=new URL(p.officialUrl);
 assert.equal(u.protocol,'https:');
 assert.ok(domains.some(d=>u.hostname===d||u.hostname.endsWith('.'+d)),p.officialUrl);
}
assert.match(page,/15 montres comparées en détail/,'The legacy in-depth selector remains clearly labeled as a 15-watch subset');
assert.match(page,/Explorer les 52 montres/,'The homepage promotes the complete 52-watch catalogue');
assert.match(page,/id="affGrid"/);
assert.match(page,/id="affSavedCount"/);
assert.match(page,/liens rémunérés, lorsqu'ils sont actifs, sont identifiés clairement/,'The source storefront must truthfully disclose possible tracked links');
assert.match(page,/id="affSearch"/);
assert.match(code,/x\.affiliateEnabled!==false/);
assert.match(code,/p\.affiliateUrl===null/);
assert.match(code,/\.textContent=/);
assert.doesNotMatch(code,/innerHTML\s*=/);
assert.match(css,/@media\(max-width:620px\)/);
const ownPage=read('site/marque.html'),ownCode=read('site/marque.js'),ownCss=read('site/marque.css');
assert.match(ownPage,/id="brandModels"/);
assert.match(ownPage,/Aucun modèle n'est encore fabriqué/);
assert.match(ownPage,/aucun paiement ni aucune commande/);
assert.match(ownCode,/atelier-emeraude/);
assert.match(ownCode,/atelier-glacier/);
assert.match(ownCode,/atelier-minuit/);
assert.match(ownCode,/localStorage\.setItem/);
assert.doesNotMatch(ownCode,/innerHTML\s*=|stripe\.|fetch\s*\(/);
assert.match(ownCss,/@media\(max-width:600px\)/);
assert.match(read('site/index.html'),/href="\.\/affiliation\.html"/);
assert.match(read('site/index.html'),/href="\.\/marque\.html"/);
assert.equal(JSON.parse(read('site/config.json')).checkoutMode,'inactive');
